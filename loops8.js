// FOR LOOP
// Runs a block of code multiple times

for (let i = 1; i <= 5; i++) {
    console.log("For Loop Count:", i);
}


// WHILE LOOP
// Executes while the condition is true

let count = 1;

while (count <= 3) {
    console.log("While Loop Count:", count);
    count++;
}


// FOR...OF LOOP
// Used to iterate arrays

