// 1. VARIABLES
// =====================================================

// 'let' is used for variables that can change
let age = 25;
console.log("Age:", age);

// 'const' is used for fixed values
const country = "India";
console.log("Country:", country);

// 'var' is the older way to declare variables
var city = "Delhi";
console.log("City:", city);

// Updating a variable
age = 26;
console.log("Updated Age:", age);